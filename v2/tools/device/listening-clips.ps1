# Listening clips: the same short passage played by v1 and then by v2 through each real output path in turn, so
# a person can hear the timing difference. THIS SENDS REAL MIDI DATA TO THE DEVICE AND MAKES SOUND (unless -DryRun).
# It changes no audio setting (no mute, no volume, no device switch).
#
#   .\v2\tools\device\listening-clips.ps1 -DryRun                    # output "null" everywhere: no device, no sound
#   .\v2\tools\device\listening-clips.ps1 -Pause 15                  # 15 s of quiet before every clip
#   .\v2\tools\device\listening-clips.ps1 -GoFile C:\path\go.txt     # before every clip: wait until that file exists
#   .\v2\tools\device\listening-clips.ps1                            # before every clip: wait for Enter in the console
#   -Fixture <mid>   play this file instead of the generated tune (it is only read, never changed or copied)
#   -Seconds 12      length of the generated tune
#   -Paths winmm-system,kdmapi,winmm-wrp   (default: all three, in this order)
#
# Order: for each path, v1 first and then v2 (an A/B pair), so with the default three paths there are 6 clips:
#   CLIP 1 of 6: v1 - OmniMIDI via system WinMM        CLIP 2 of 6: v2 - OmniMIDI via system WinMM
#   CLIP 3 of 6: v1 - OmniMIDI via KDMAPI              CLIP 4 of 6: v2 - OmniMIDI via KDMAPI
#   CLIP 5 of 6: v1 - OmniMIDI via WinMM with winmmwrp CLIP 6 of 6: v2 - OmniMIDI via WinMM with winmmwrp
# Each "CLIP n of N: ..." line is printed BEFORE the wait, so whoever runs this can announce the clip first.
# The clip plays right after the wait. The data is played at the file's own tempo, as it is.
#
# The passage (generated by listening-tune.ps1, ~12 s): the theme of "Ode to Joy" on piano with chords and bass (about 3.4 s),
# then three fast arpeggio rolls on a celesta sound at about 1,000, 4,000 and 10,000 events per second (about
# 1.4 s each, 0.3 s of rest between) - the part where v1's timing in bunches every 1-2 ms (with OmniMIDI loaded)
# can be heard against v2's event-by-event timing - then the theme's ending (about 3.4 s). Velocities 64 to 100.
#
# The winmmwrp path needs the third-party winmm.dll: it is copied ONLY into a git-ignored private folder under
# v2\out\device-test\ next to private copies of the two programs, and deleted when the script ends.
param(
    [string]$Fixture = '',
    [double]$Seconds = 12,
    [switch]$DryRun,
    [double]$Pause = 0,
    [string]$GoFile = '',
    [ValidateSet('x64', 'x86')][string]$Arch = 'x64',
    [string[]]$Paths = @('winmm-system', 'kdmapi', 'winmm-wrp'),
    [string]$V1Exe,
    [string]$V2Exe,
    [string]$WinmmWrp = $env:MIDIBN_WINMMWRP_DLL   # path of the winmmwrp winmm.dll; required for winmm-wrp (or set MIDIBN_WINMMWRP_DLL)
)
$ErrorActionPreference = 'Stop'
$Paths = @($Paths | ForEach-Object { $_ -split ',' } | Where-Object { $_ })
$root = (Resolve-Path (Join-Path (Split-Path -Parent $MyInvocation.MyCommand.Path) '..\..\..')).Path
$deviceDir = Join-Path $root 'v2\out\device-test'
$dash = [string][char]0x2014
if (-not $V2Exe) { $V2Exe = Join-Path $root "v2\out\build-$Arch\Release\midibn-device-measure.exe" }
if (-not $V1Exe) { $V1Exe = Join-Path $root "v2\out\device-test\v1-$Arch\v1-device.exe" }
foreach ($e in $V1Exe, $V2Exe) { if (-not (Test-Path -LiteralPath $e)) { throw "program not found: $e (build with run-device-measurements.ps1 -Build)" } }
$pathText = @{ 'winmm-system' = 'OmniMIDI via system WinMM'; 'kdmapi' = 'OmniMIDI via KDMAPI'; 'winmm-wrp' = 'OmniMIDI via WinMM with winmmwrp' }
$pathOutput = @{ 'winmm-system' = 'winmm'; 'kdmapi' = 'kdmapi'; 'winmm-wrp' = 'winmm' }
foreach ($p in $Paths) { if (-not $pathText.ContainsKey($p)) { throw "unknown path '$p' (winmm-system, kdmapi, winmm-wrp)" } }

if (-not $DryRun -and $Pause -le 0 -and -not $GoFile -and [Console]::IsInputRedirected) {
    throw 'No console to press Enter in: give -Pause <seconds> or -GoFile <file>, or use -DryRun.'
}

# ---- the passage
$stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
$outDir = Join-Path $deviceDir "listening\$stamp$(if ($DryRun) { '-dryrun' })"
New-Item -ItemType Directory -Force -Path $outDir | Out-Null
if ($Fixture) {
    if (-not (Test-Path -LiteralPath $Fixture)) { throw "fixture not found: $Fixture" }
    $passage = (Resolve-Path -LiteralPath $Fixture).Path
    $passageText = 'the given file (read only)'
}
else {
    . (Join-Path $PSScriptRoot 'listening-tune.ps1')
    $fixDir = Join-Path $deviceDir 'fixtures'
    $passage = Join-Path $fixDir ('listening-tune-{0}s.mid' -f $Seconds.ToString('0.##', [Globalization.CultureInfo]::InvariantCulture))
    $info = New-ListeningTune -Path $passage -Seconds $Seconds
    $passageText = "generated tune ($info)"
}

# ---- the winmmwrp private copies
$wrpDir = Join-Path $deviceDir "$Arch-winmmwrp-listening"
$wrpExe = @{}
if ($Paths -contains 'winmm-wrp' -and -not $DryRun) {
    if (-not $WinmmWrp) { throw "winmm-wrp: no winmmwrp DLL given: pass -WinmmWrp <path to the winmmwrp winmm.dll> or set the environment variable MIDIBN_WINMMWRP_DLL (or leave winmm-wrp out of -Paths)" }
    if (-not (Test-Path -LiteralPath $WinmmWrp)) { throw "winmm-wrp needs $WinmmWrp (or leave winmm-wrp out of -Paths)" }
    $b = [IO.File]::ReadAllBytes($WinmmWrp)
    $machine = [BitConverter]::ToUInt16($b, [BitConverter]::ToInt32($b, 0x3C) + 4)
    $expected = if ($Arch -eq 'x64') { 0x8664 } else { 0x014C }
    if ($machine -ne $expected) { throw ("the winmmwrp DLL is PE machine 0x{0:X4}, not {1}" -f $machine, $Arch) }
}
function Get-ClipExe([string]$program, [string]$pathName) {
    $exe = if ($program -eq 'v1') { $V1Exe } else { $V2Exe }
    if ($pathName -ne 'winmm-wrp' -or $DryRun) { return $exe }
    if (-not $wrpExe.ContainsKey($program)) {
        $dir = Join-Path $wrpDir $program
        New-Item -ItemType Directory -Force -Path $dir | Out-Null
        Copy-Item -LiteralPath $exe -Destination (Join-Path $dir (Split-Path -Leaf $exe)) -Force
        Copy-Item -LiteralPath $WinmmWrp -Destination (Join-Path $dir 'winmm.dll') -Force
        $wrpExe[$program] = Join-Path $dir (Split-Path -Leaf $exe)
    }
    return $wrpExe[$program]
}

function Wait-ForGo([int]$n, [int]$total) {
    if ($DryRun -and $Pause -le 0 -and -not $GoFile) { return }
    if ($GoFile) {
        Write-Host "   (waiting for the file $GoFile; it is deleted when seen)"
        while (-not (Test-Path -LiteralPath $GoFile)) { Start-Sleep -Milliseconds 300 }
        Remove-Item -LiteralPath $GoFile -Force -ErrorAction SilentlyContinue
        return
    }
    if ($Pause -gt 0) {
        Write-Host ("   (starting in {0} s)" -f $Pause)
        Start-Sleep -Milliseconds ([int]($Pause * 1000))
        return
    }
    Write-Host '   (press Enter to start this clip)'
    [void][Console]::ReadLine()
}

$clips = @()
foreach ($p in $Paths) { foreach ($program in 'v1', 'v2') { $clips += [pscustomobject]@{ Program = $program; Path = $p } } }
$plan = (& powercfg.exe /getactivescheme 2>$null) -join ' '
Write-Host ''
Write-Host ("LISTENING CLIPS: {0} clips of about {1} s. Passage: {2}." -f $clips.Count, $Seconds, $passageText)
if ($DryRun) { Write-Host 'DRY RUN: every clip uses output "null": no device is opened and nothing can be heard.' }
else { Write-Host 'REAL RUN: MIDI data is sent to the OmniMIDI device and will be heard at the PC''s current volume. No audio setting is changed.' }
Write-Host "Power plan: $plan"
Write-Host ''
$failed = @()
try {
    for ($i = 0; $i -lt $clips.Count; $i++) {
        $c = $clips[$i]
        $n = $i + 1
        Write-Host ("CLIP {0} of {1}: {2} {3} {4}{5}" -f $n, $clips.Count, $c.Program, $dash, $pathText[$c.Path], $(if ($DryRun) { ' (dry run: null output)' } else { '' }))
        Wait-ForGo $n $clips.Count
        $output = if ($DryRun) { 'null' } else { $pathOutput[$c.Path] }
        if ($DryRun -and $output -ne 'null') { throw 'dry run refuses a real output' }
        $exe = Get-ClipExe $c.Program $c.Path
        $label = "clip$n-$($c.Program)-$($c.Path)"
        $clock = [Diagnostics.Stopwatch]::StartNew()
        Write-Host ("   playing clip {0} ..." -f $n)
        $ErrorActionPreference = 'Continue'   # a program's stderr text is data here, not a script failure
        $out = & $exe run --output $output --fixture $passage --out $outDir --label $label --repeats 1 --instr none --warm 0 --settle-ms 200 --device-name OmniMIDI --cleanup-log (Join-Path $outDir "$label.cleanup.txt") 2>&1
        $code = $LASTEXITCODE
        $ErrorActionPreference = 'Stop'
        $clock.Stop()
        $out | ForEach-Object { "$_" } | Set-Content -LiteralPath (Join-Path $outDir "$label.stdout.txt") -Encoding UTF8
        $ended = ($out | ForEach-Object { "$_" } | Select-String 'ended_ms=([0-9.]+)' | Select-Object -First 1)
        if ($code -ne 0) { $failed += $label; Write-Host ("   CLIP {0} FAILED: exit code {1}" -f $n, $code); ($out | ForEach-Object { "      $_" }) | Write-Host }
        else { Write-Host ("   clip {0} finished after {1:N1} s{2}" -f $n, $clock.Elapsed.TotalSeconds, $(if ($ended) { " (playback $($ended.Matches[0].Groups[1].Value) ms)" } else { '' })) }
        Start-Sleep -Milliseconds 800
    }
}
finally {
    if (Test-Path -LiteralPath $wrpDir) { Remove-Item -LiteralPath $wrpDir -Recurse -Force -ErrorAction SilentlyContinue }
}
Write-Host ''
if ($failed.Count -gt 0) { Write-Host ("LISTENING-CLIPS: FAIL ({0})" -f ($failed -join ', ')); exit 1 }
Write-Host ("LISTENING-CLIPS: DONE {0} clips{1}" -f $clips.Count, $(if ($DryRun) { ' (dry run, no sound)' } else { '' }))
exit 0

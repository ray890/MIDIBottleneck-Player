# Full parity run:
#  1. regenerates v1 reference traces with the v1 harness (x64 and x86) and
#     checks they still equal the committed expected traces (drift check):
#     load/index traces, flow traces (x86 = pointer size 4, x64 = 8), decimal ops,
#     model traces (both architectures against the same expected trace);
#     and, when the v1 engine spike is built, regenerates v1's engine recordings (v1's real PlaybackEngine under
#     the lock-step virtual clock, v2\harness\v1-reference\spike) and checks their SHA-256 digests against
#     expected\engine (make-engine-expected.ps1 -Check);
#  2. runs the v2 parity checker for every built variant (x64, x86, XP, XP IA32). Tier 1: v1. Every difference from
#     v1's traces and engine recordings must be explained by a rule of expected\differences-from-v1.txt (each rule
#     belongs to an entry of v2\docs\DIFFERENCES_FROM_V1.md); the engine scenarios run on every engine fixture under
#     the v2 lock-step harness, comparing recording digests with v1's. Tier 2: v2's output must equal its own
#     recorded baseline (v2\harness\expected-v2\, regenerated by v2\harness\make-v2-baseline.ps1) exactly.
#  3. checks that every rule id of the rule file has an entry in the register.
# Prerequisites: v2\harness\v1-reference\build.ps1, v2\harness\fixtures\generate.ps1 -Large,
# and the CMake builds described in v2\BUILDING.md.
$ErrorActionPreference = 'Stop'
$repo = (Resolve-Path (Join-Path (Split-Path -Parent $MyInvocation.MyCommand.Path) '..\..')).Path
Set-Location $repo
[Environment]::CurrentDirectory = $repo   # the .NET tools resolve relative paths against this
$fixtures = 'v2\harness\fixtures'
$expected = 'v2\harness\expected'
$large = 'v2\harness\fixtures\large\large-8m.mid'
# Routing 1,000,000-held-notes limit: generated on demand (generate.ps1 -Large), compared only when present.
$largeDir = 'v2\harness\fixtures\large'
$largeRouting = "$largeDir\routing-held-1000001.mid"
$largeRoutingTrace = 'v2\harness\expected\models-large\routing-large.trace'
$failures = 0
$modelFamilies = @('rate', 'queue', 'ordered', 'pernote', 'delayed', 'attack', 'outputrate', 'analysis', 'routing')

function Strip([string]$path) {
    ([System.IO.File]::ReadAllText($path) -split "`n" | Where-Object { -not $_.StartsWith('#') }) -join "`n"
}

Write-Host '== v1 reference drift check'
$fresh = 'v2\out\v1-fresh'
New-Item -ItemType Directory -Force -Path $fresh | Out-Null
foreach ($arch in 'x64', 'x86') {
    $exe = "v2\out\v1-reference\$arch\v1-reference.exe"
    $ptr = if ($arch -eq 'x64') { 8 } else { 4 }
    $drift = 0
    foreach ($file in Get-ChildItem $fixtures -File | Where-Object { $_.Extension -in '.mid', '.rmi' }) {
        $stem = $file.BaseName + $file.Extension.Replace('.', '-')
        & $exe dump $file.FullName --out "$fresh\$stem.trace"
        if ((Strip "$fresh\$stem.trace") -ne (Strip "$expected\$stem.trace")) { Write-Host "  DRIFT $arch $stem"; $drift++ }
        & $exe flow $file.FullName --out "$fresh\$stem.flow.trace"
        if ((Strip "$fresh\$stem.flow.trace") -ne (Strip "$expected\flow\$stem.ptr$ptr.trace")) { Write-Host "  DRIFT $arch flow $stem"; $drift++ }
    }
    & $exe decimal-ops 20261012 "$fresh\decimal-ops.txt"
    if ((Strip "$fresh\decimal-ops.txt") -ne (Strip "$expected\decimal-ops.txt")) { Write-Host "  DRIFT $arch decimal-ops"; $drift++ }
    foreach ($family in $modelFamilies) {
        & $exe models $family $fixtures "$fresh\model-$family.trace"
        if ((Strip "$fresh\model-$family.trace") -ne (Strip "$expected\models\$family.trace")) { Write-Host "  DRIFT $arch model $family"; $drift++ }
    }
    if (Test-Path $large) {
        & $exe dump $large --summary --out "$fresh\large.trace"
        if ((Strip "$fresh\large.trace") -ne (Strip "$expected\large-8m-mid.summary.trace")) { Write-Host "  DRIFT $arch large"; $drift++ }
        & $exe flow $large --summary --out "$fresh\large.flow.trace"
        if ((Strip "$fresh\large.flow.trace") -ne (Strip "$expected\flow\large-8m-mid.ptr$ptr.summary.trace")) { Write-Host "  DRIFT $arch large flow"; $drift++ }
    }
    if ((Test-Path $largeRouting) -and (Test-Path "$largeDir\routing-held-1000000.mid")) {
        $routingTime = Measure-Command { & $exe models routing-large $largeDir "$fresh\model-routing-large.trace" }
        if ((Strip "$fresh\model-routing-large.trace") -ne (Strip $largeRoutingTrace)) { Write-Host "  DRIFT $arch model routing-large"; $drift++ }
        Write-Host ("  v1 {0} routing-large: {1:N1} s" -f $arch, $routingTime.TotalSeconds)
    }
    Write-Host ("  v1 {0}: {1}" -f $arch, $(if ($drift -eq 0) { 'identical to committed expected traces' } else { "$drift differences" }))
    $failures += $drift
}

Write-Host '== v1 engine recordings drift check'
$engineV1Files = 'v2\out\spike\runs-lockstep-parity-drift\x64\run1'
$spikeExes = @('v2\out\spike\x64\rendezvous-spike.exe', 'v2\out\spike\x86\rendezvous-spike.exe')
if ((Test-Path $spikeExes[0]) -and (Test-Path $spikeExes[1])) {
    # Regenerates v1's recordings (about 4 minutes per architecture) and compares their digests with the committed ones.
    & .\v2\harness\v1-reference\spike\run-spike.ps1 -AllValid -Runs 1 -Tag parity-drift | Select-Object -Last 1 | ForEach-Object { Write-Host "  $_" }
    if ($LASTEXITCODE -ne 0) { Write-Host '  DRIFT: the v1 spike runs were not identical across architectures'; $failures++ }
    else {
        & .\v2\harness\make-engine-expected.ps1 -RunRoot v2\out\spike\runs-lockstep-parity-drift -Check
        if ($LASTEXITCODE -ne 0) { $failures++ }
    }
}
else { Write-Host '  v1 engine spike not built (v2\harness\v1-reference\spike\build-spike.ps1), skipped' }

Write-Host '== improvement register check'
$register = [IO.File]::ReadAllText('v2\docs\DIFFERENCES_FROM_V1.md')
$ruleIds = @([IO.File]::ReadAllLines("$expected\differences-from-v1.txt") | Where-Object { $_ -match '^(trace|insert|delete|engine)\s+(DD-\d+)\s' } | ForEach-Object { ($_ -split '\s+')[1] } | Sort-Object -Unique)
foreach ($id in $ruleIds) {
    if ($register -notmatch "(?m)^## $id\b") { Write-Host "  FAIL: rule id $id has no entry in v2\docs\DIFFERENCES_FROM_V1.md"; $failures++ }
}
Write-Host ("  {0} register id(s) used by rules" -f $ruleIds.Count)

foreach ($variant in @(@('x64','v2\out\build-x64\Release\midibn-parity.exe'),
                       @('x86', 'v2\out\build-x86\Release\midibn-parity.exe'),
                       @('xp',  'v2\out\build-xp\Release\v2-xp-selftest.exe'),
                       @('xp-ia32', 'v2\out\build-xp-ia32\Release\v2-xp-selftest-ia32.exe'))) {
    if (-not (Test-Path $variant[1])) { Write-Host "== v2 $($variant[0]): not built, skipped"; continue }
    Write-Host "== v2 $($variant[0])"
    $arguments = @('--fixtures', $fixtures, '--expected', $expected, '--baseline', 'v2\harness\expected-v2', '--scenarios', 'v2\harness\engine-scenarios.txt')
    if (Test-Path $engineV1Files) { $arguments += @('--engine-v1', $engineV1Files) }   # first differing line of any engine mismatch
    if (Test-Path $large) { $arguments += @('--large', $large, '--large-expected', "$expected\large-8m-mid.summary.trace") }
    if ((Test-Path $largeRouting) -and (Test-Path "$largeDir\routing-held-1000000.mid")) { $arguments += @('--large-model', $largeRoutingTrace, '--large-model-fixtures', $largeDir) }
    $output = & $variant[1] @arguments
    $output | Where-Object { $_ -match '^(FAIL|RESULT|note engine|note rule|register |PASS engine|PASS v2 baseline)' -or $_ -match '^PASS .*explained' -or $_ -match '^\s+(expected|actual|baseline|first difference|v1:|v2:|explained by)' } | ForEach-Object { Write-Host "  $_" }
    if ($LASTEXITCODE -ne 0) { $failures++ }
}
if ($failures -ne 0) { Write-Host "PARITY: FAIL ($failures)"; exit 1 }
Write-Host 'PARITY: PASS'
